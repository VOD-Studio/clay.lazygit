-- Generates themes/clay.yml from clay.nvim's palette, the single source of
-- Clay colors. Usage: lua scripts/build.lua [path/to/palette.lua]
-- The palette path defaults to $CLAY_PALETTE, then a sibling clay.nvim checkout.

local palette_path = arg[1] or os.getenv("CLAY_PALETTE") or "../clay.nvim/lua/clay/palette.lua"
local palette = dofile(palette_path)

-- Lazygit theme field -> palette key, then modifiers. Roles follow
-- design/clay-design-system.md: Clay marks focus only, every other state is a
-- gray step, and related states never share a color.
local roles = {
  { "activeBorderColor", "clay", "bold" }, -- focus
  { "searchingActiveBorderColor", "bright", "bold" }, -- distinct from focus
  { "inactiveBorderColor", "float_border" },
  { "optionsTextColor", "comment" }, -- hints
  { "selectedLineBgColor", "selection" },
  { "inactiveViewSelectedLineBgColor", "cursorline" }, -- closer to bg than selection
  { "cherryPickedCommitFgColor", "bright" },
  { "cherryPickedCommitBgColor", "search" }, -- farther than selection
  { "markedBaseCommitFgColor", "bg" },
  { "markedBaseCommitBgColor", "secondary" },
  { "unstagedChangesColor", "secondary" }, -- modified
  { "defaultFgColor", "fg" },
}
local author_color = "muted"

local variants = { "dark", "light" }

local function color(variant, key)
  local value = palette[variant][key]
  if value == nil then
    error(("palette.%s.%s is missing in %s"):format(variant, key, palette_path))
  end
  return value
end

-- States that can appear together must not share a color (design rule 6).
local distinct = {
  { "activeBorderColor", "searchingActiveBorderColor", "inactiveBorderColor" },
  {
    "selectedLineBgColor",
    "inactiveViewSelectedLineBgColor",
    "cherryPickedCommitBgColor",
    "markedBaseCommitBgColor",
  },
  { "unstagedChangesColor", "defaultFgColor" },
}

local role_key = {}
for _, role in ipairs(roles) do
  role_key[role[1]] = role[2]
end

for _, variant in ipairs(variants) do
  for _, group in ipairs(distinct) do
    local seen = {}
    for _, field in ipairs(group) do
      local value = color(variant, role_key[field])
      if seen[value] then
        error(("%s: %s and %s share %s"):format(variant, seen[value], field, value))
      end
      seen[value] = field
    end
  end
end

local out = {
  "# Clay theme for lazygit. Generated by scripts/build.lua from clay.nvim's",
  "# lua/clay/palette.lua; edit the generator, not this file.",
  "gui:",
  "  theme:",
  "    # Keep the text colors of the selected line; the background marks it.",
  "    selectedLineFgColor:",
  "      - default",
}

for _, variant in ipairs(variants) do
  out[#out + 1] = ("  %sTheme:"):format(variant)
  for _, role in ipairs(roles) do
    out[#out + 1] = ("    %s:"):format(role[1])
    out[#out + 1] = ('      - "%s" # %s'):format(color(variant, role[2]), role[2])
    for i = 3, #role do
      out[#out + 1] = ("      - %s"):format(role[i])
    end
  end
  out[#out + 1] = "    authorColors:"
  out[#out + 1] = ('      "*": "%s" # %s'):format(color(variant, author_color), author_color)
end

io.write(table.concat(out, "\n"), "\n")
